#!/usr/bin/env python3
"""Embed the upstream licence texts as byte arrays (build time).

Usage: python3 -I gen_licenses.py <LICENSE.pgvector> <LICENSE.postgresql> <out.h>
"""
import sys


def array(name: str, path: str) -> str:
    with open(path, "rb") as f:
        data = f.read()
    rows = []
    for i in range(0, len(data), 16):
        rows.append("    " + ", ".join("0x%02x" % b for b in data[i : i + 16]) + ",")
    rows.append("    0x00")
    return "static const unsigned char %s[] = {\n%s\n};\n" % (name, "\n".join(rows))


def main() -> int:
    if len(sys.argv) != 4:
        print("usage: gen_licenses.py <pgvector> <postgresql> <out.h>", file=sys.stderr)
        return 2
    out = [
        "/* Generated by cmake/gen_licenses.py. Do not edit. */",
        "#ifndef AV_LICENSES_H",
        "#define AV_LICENSES_H",
        "",
        array("av_license_pgvector", sys.argv[1]),
        array("av_license_postgresql", sys.argv[2]),
        "#endif /* AV_LICENSES_H */",
        "",
    ]
    with open(sys.argv[3], "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
