#!/usr/bin/env python3
"""Generate av_error_table.h from spec/error-codes.json (build time only, no runtime JSON).

Usage: python3 -I gen_error_table.py <error-codes.json> <out.h>
"""
import json
import sys


def title_of(code: str) -> str:
    words = code.replace("_", " ")
    return words[0].upper() + words[1:]


def c_str(s: str) -> str:
    return json.dumps(s)  # JSON string escapes are valid C for the ASCII we use


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: gen_error_table.py <error-codes.json> <out.h>", file=sys.stderr)
        return 2
    with open(sys.argv[1], encoding="utf-8") as f:
        doc = json.load(f)
    lines = [
        "/* Generated by cmake/gen_error_table.py from spec/error-codes.json. Do not edit. */",
        "#ifndef AV_ERROR_TABLE_H",
        "#define AV_ERROR_TABLE_H",
        "",
        f"#define AV_ERROR_SPEC_VERSION {c_str(doc['spec_version'])}",
        f"#define AV_ERROR_TYPE_PREFIX {c_str(doc['type_prefix'])}",
        "",
        "typedef struct {",
        "    const char *code;",
        "    const char *title;",
        "    int status;",
        "    int retryable;",
        "} av_error_info;",
        "",
        "static const av_error_info av_error_table[] = {",
    ]
    for e in doc["errors"]:
        lines.append(
            "    {%s, %s, %d, %d},"
            % (c_str(e["code"]), c_str(title_of(e["code"])), e["status"], 1 if e["retryable"] else 0)
        )
    lines += ["};", "", "#endif /* AV_ERROR_TABLE_H */", ""]
    with open(sys.argv[2], "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
